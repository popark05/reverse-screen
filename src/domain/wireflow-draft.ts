import type { DiscoveryEvent } from "./discovery-event.js";
import type { DiscoverySession } from "./discovery-session.js";

/**
 * Request body for Wireflow Review `POST /v1/flows/import`
 * (see wireflow-review docs/architecture/flow-contract.md). Field names follow that
 * contract (camelCase, 1.1 for origin "discovered"); IDs are copied verbatim from Discovery Events.
 */
export interface WireflowDraft {
  applicationId: string;
  title: string;
  description: string;
  nodes: Array<{
    nodeId: string;
    type: "screen";
    title: string;
    origin: "discovered";
    discoveryRef: { sourceSystem: "reverse-screen"; screenId: string; sessionId: string };
  }>;
  edges: Array<{
    edgeId: string;
    fromNodeId: string;
    toNodeId: string;
    label: string;
    trigger: string;
    kind: "primary" | "back";
    origin: "discovered";
    discoveryRef: { sourceSystem: "reverse-screen"; transitionId: string; sessionId: string };
  }>;
}

/** Action-driven transitions that change what the user sees. Hybrid lifecycle and no_change are not flow edges. */
const FLOW_TRANSITION_KINDS = new Set(["navigation", "state_change"]);
const MAX_TEXT = 240;
const clip = (value: string) => (value.length > MAX_TEXT ? `${value.slice(0, MAX_TEXT - 1)}…` : value);

/**
 * Builds a wireflow draft from one discovery session: every observed screen becomes a node
 * (titled by its first observed name) and every distinct action-driven transition an edge.
 * Node IDs are the screen IDs and edge IDs derive from transition IDs, so re-exporting the
 * same session is stable. Returns undefined when no screen was observed.
 */
export function buildWireflowDraft(session: DiscoverySession, events: DiscoveryEvent[]): WireflowDraft | undefined {
  const ordered = [...events].sort((a, b) => a.sequence - b.sequence);
  const ref = { sourceSystem: "reverse-screen" as const, sessionId: session.session_id };

  // Native screen IDs are deterministic; WebView screen IDs are per observation, so WebView
  // screens are only included when an action transition actually reaches or leaves them.
  const referenced = new Set<string>();
  for (const event of ordered) {
    if (event.event_type !== "transition_observed" || !FLOW_TRANSITION_KINDS.has(String(event.payload.transition_kind))) continue;
    referenced.add(String(event.payload.source_screen_id ?? ""));
    referenced.add(String(event.payload.target_screen_id ?? ""));
  }
  const nodes = new Map<string, WireflowDraft["nodes"][number]>();
  for (const event of ordered) {
    if (event.event_type !== "screen_observed" || !event.screen_id || nodes.has(event.screen_id)) continue;
    if (event.payload.context_type === "webview" && !referenced.has(event.screen_id)) continue;
    const name = typeof event.payload.name === "string" && event.payload.name.trim()
      ? event.payload.name.trim()
      : typeof event.payload.title === "string" && event.payload.title.trim() ? event.payload.title.trim() : "Untitled screen";
    nodes.set(event.screen_id, {
      nodeId: event.screen_id, type: "screen", title: clip(name), origin: "discovered",
      discoveryRef: { ...ref, screenId: event.screen_id }
    });
  }
  if (nodes.size === 0) return undefined;

  const edges = new Map<string, WireflowDraft["edges"][number]>();
  for (const event of ordered) {
    const payload = event.payload;
    if (event.event_type !== "transition_observed" || !event.transition_id || edges.has(event.transition_id)) continue;
    if (!FLOW_TRANSITION_KINDS.has(String(payload.transition_kind))) continue;
    const from = String(payload.source_screen_id ?? "");
    const to = String(payload.target_screen_id ?? "");
    if (!nodes.has(from) || !nodes.has(to)) continue;
    const action = String(payload.action ?? "tap");
    const label = action === "back"
      ? "Back"
      : String(payload.locator_value ?? payload.locator_name ?? action);
    edges.set(event.transition_id, {
      edgeId: `transition-${event.transition_id}`, fromNodeId: from, toNodeId: to,
      label: clip(label), trigger: action, kind: action === "back" ? "back" : "primary", origin: "discovered",
      discoveryRef: { ...ref, transitionId: event.transition_id }
    });
  }

  return {
    applicationId: session.application_id,
    title: clip(`${session.application_id} — discovered on ${session.platform} ${session.target_id}`),
    description: `Generated by Reverse Screen from discovery session ${session.session_id}. ` +
      "Screens and transitions are runtime observations and still need human review.",
    nodes: [...nodes.values()],
    edges: [...edges.values()]
  };
}
